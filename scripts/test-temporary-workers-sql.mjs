  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE SCHEMA auth;
    CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT NULLIF(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    CREATE TABLE profiles(id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE, organization_id uuid, role text DEFAULT 'employee', full_name text, email text, phone text, job_title text, hourly_rate numeric DEFAULT 0, cost_rate numeric DEFAULT 0, is_active boolean DEFAULT true, show_wage_in_profile boolean DEFAULT true);
    CREATE TABLE attendance_logs(id serial PRIMARY KEY, user_id uuid REFERENCES profiles(id) ON DELETE CASCADE, hours numeric);
    INSERT INTO auth.users VALUES ('${admin}'),('${employee}'),('${otherAdmin}');
    INSERT INTO profiles(id,organization_id,role,full_name) VALUES ('${admin}','${org}','admin','Admin'),('${employee}','${org}','employee','Core'),('${otherAdmin}','${otherOrg}','admin','Other');
    INSERT INTO attendance_logs(user_id,hours) VALUES ('${employee}',8.25);`);
  const migration = readFileSync(new URL('../supabase_temporary_workers.sql', import.meta.url), 'utf8');
  await db.exec(migration);
  await db.exec(migration);
  const login = id => db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [id]);
  const save = async payload => (await db.query('SELECT public.save_temporary_worker($1::jsonb) AS id', [JSON.stringify(payload)])).rows[0].id;
  await login(admin);
  const id = await save({ full_name: 'Brigádnik', job_title: 'Brigádnik', temporary_periods: [{ start_date: '2026-11-06', end_date: '2026-11-08' }] });
  let record = (await db.query('SELECT * FROM profiles WHERE id=$1', [id])).rows[0];
  assert.equal(record.is_temporary, true); assert.equal(record.auth_user_id, null); assert.equal(record.email, null);
  assert.equal((await db.query('SELECT count(*) FROM auth.users')).rows[0].count, 3);
  const positionMigration = readFileSync(new URL('../supabase_temporary_worker_position.sql', import.meta.url), 'utf8');
  await db.exec(positionMigration);
  await db.exec(positionMigration);
  assert.equal((await db.query('SELECT job_title FROM profiles WHERE id=$1',[id])).rows[0].job_title,'Brigádnik');
  await save({id,full_name:'Brigádnik',job_title:'  Tesár na výpomoc  '});
  assert.equal((await db.query('SELECT job_title FROM profiles WHERE id=$1',[id])).rows[0].job_title,'Tesár na výpomoc');
  await assert.rejects(save({id,full_name:'Brigádnik',job_title:'a'.repeat(121)}));
  assert.equal((await db.query('SELECT job_title FROM profiles WHERE id=$1',[id])).rows[0].job_title,'Tesár na výpomoc');
  await db.query('INSERT INTO attendance_logs(user_id,hours) VALUES ($1,8.25)', [id]);
  await save({ id, full_name: 'Brigádnik', default_payment_type: 'fixed', default_fixed_amount: 150, temporary_periods: [{ start_date: '2026-11-06', end_date: '2026-11-08' }, { start_date: '2026-12-01', end_date: '2026-12-02' }] });
  record = (await db.query('SELECT * FROM profiles WHERE id=$1', [id])).rows[0];
  assert.equal(Number(record.default_fixed_amount), 150); assert.equal(record.temporary_periods.length, 2);
  await assert.rejects(save({ id, full_name: 'Bad', temporary_periods: [{ start_date: '2026-11-06', end_date: '2026-11-05' }] }));
  assert.equal((await db.query('SELECT full_name FROM profiles WHERE id=$1', [id])).rows[0].full_name, 'Brigádnik');
  await assert.rejects(save({ id: employee, full_name: 'Cannot replace core' }));
  await assert.rejects(db.query('UPDATE profiles SET is_temporary=false WHERE id=$1', [id]));
  await login(employee); await assert.rejects(save({ full_name: 'Forbidden' }));
  await login(otherAdmin); await assert.rejects(save({ id, full_name: 'Wrong company' }));
  await login(admin);
  const newAccount = '00000000-0000-0000-0000-000000000004';
  await save({ id, full_name: 'Brigádnik', temporary_periods: [{ start_date: '2000-01-01', end_date: '2000-01-02' }] });
