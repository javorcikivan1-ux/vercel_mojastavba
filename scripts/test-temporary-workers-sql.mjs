  await db.query('DELETE FROM auth.users WHERE id=$1', [employee]);
  assert.equal((await db.query('SELECT count(*) FROM profiles WHERE id=$1', [employee])).rows[0].count, 0);
  assert.equal((await db.query('SELECT count(*) FROM attendance_logs WHERE user_id=$1', [id])).rows[0].count, 1);
